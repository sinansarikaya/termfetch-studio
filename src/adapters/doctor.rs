use crate::paths::Paths;
use std::path::{Path, PathBuf};
use std::process::Command;

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Level {
    Ok,
    Info,
    Warn,
    Fail,
}

impl Level {
    pub fn symbol(self) -> &'static str {
        match self {
            Self::Ok => "✓",
            Self::Info => "•",
            Self::Warn => "⚠",
            Self::Fail => "✗",
        }
    }
}

#[derive(Debug, Clone)]
pub struct Check {
    pub name: &'static str,
    pub level: Level,
    pub detail: String,
}

fn check(name: &'static str, level: Level, detail: impl Into<String>) -> Check {
    Check {
        name,
        level,
        detail: detail.into(),
    }
}

fn has_command(cmd: &str) -> bool {
    Command::new(cmd)
        .arg("--version")
        .stdout(std::process::Stdio::null())
        .stderr(std::process::Stdio::null())
        .status()
        .is_ok()
}

fn validate_jsonc(name: &'static str, path: &Path) -> Check {
    match std::fs::read_to_string(path) {
        Err(_) => check(
            name,
            Level::Info,
            format!("not created yet ({})", path.display()),
        ),
        Ok(text) => match jsonc_parser::parse_to_value(&text, &Default::default()) {
            Ok(Some(_)) => {
                let origin = if text.contains(MARKER) {
                    "generated by TermFetch Studio"
                } else {
                    "hand-written"
                };
                check(
                    name,
                    Level::Ok,
                    format!("valid JSONC, {origin} ({})", path.display()),
                )
            }
            Ok(None) => check(
                name,
                Level::Warn,
                format!("empty file ({})", path.display()),
            ),
            Err(e) => check(
                name,
                Level::Fail,
                format!("invalid JSONC: {e} ({})", path.display()),
            ),
        },
    }
}

fn writable(dir: &Path) -> Result<(), String> {
    let probe = dir.join(".tfs-write-test");
    atomic_write(&probe, b"ok").map_err(|e| e.to_string())?;
    let _ = std::fs::remove_file(probe);
    Ok(())
}

pub fn shell_integration() -> Check {
    let Some(home) = directories::BaseDirs::new().map(|b| b.home_dir().to_path_buf()) else {
        return check("Shell integration", Level::Info, "home directory unknown");
    };
    let rcs = [
        ".bashrc",
        ".zshrc",
        ".config/fish/config.fish",
        "Documents/PowerShell/Microsoft.PowerShell_profile.ps1",
        "Documents/WindowsPowerShell/Microsoft.PowerShell_profile.ps1",
        ".config/powershell/Microsoft.PowerShell_profile.ps1",
    ];
    let mut found: Vec<String> = rcs
        .iter()
        .filter(|rc| std::fs::read_to_string(home.join(rc)).is_ok_and(|t| t.contains("fastfetch")))
        .map(|rc| (*rc).to_string())
        .collect();
    // Documents can be redirected (OneDrive), so look for PowerShell profiles there too.
    if let Some(docs) =
        directories::UserDirs::new().and_then(|u| u.document_dir().map(Path::to_path_buf))
    {
        for rc in [
            "PowerShell/Microsoft.PowerShell_profile.ps1",
            "WindowsPowerShell/Microsoft.PowerShell_profile.ps1",
        ] {
            let path = docs.join(rc);
            if std::fs::read_to_string(&path).is_ok_and(|t| t.contains("fastfetch")) {
                found.push(path.display().to_string());
            }
        }
    }
    if found.is_empty() {
        check(
            "Shell integration",
            Level::Info,
            "no shell rc runs fastfetch on startup",
        )
    } else {
        check(
            "Shell integration",
            Level::Ok,
            format!("fastfetch runs from {}", found.join(", ")),
        )
    }
}

fn nerd_font() -> Check {
    if let Ok(out) = Command::new("fc-list").arg(":").arg("family").output()
        && out.status.success()
    {
        let list = String::from_utf8_lossy(&out.stdout).to_ascii_lowercase();
        if list.contains("nerd font") || list.contains("nerdfont") {
            return check("Nerd Font", Level::Ok, "installed (icons render correctly)");
        } else {
            return check(
                "Nerd Font",
                Level::Warn,
                "none found; module icons may show as boxes",
            );
        }
    }

    // Fallback font directory scan for macOS / Windows or systems without fontconfig
    let mut font_dirs: Vec<PathBuf> = Vec::new();
    if let Some(home) = directories::BaseDirs::new().map(|b| b.home_dir().to_path_buf()) {
        font_dirs.push(home.join(".local/share/fonts"));
        font_dirs.push(home.join(".fonts"));
        #[cfg(target_os = "macos")]
        font_dirs.push(home.join("Library/Fonts"));
        #[cfg(windows)]
        if let Some(local) = std::env::var_os("LOCALAPPDATA") {
            font_dirs.push(PathBuf::from(local).join(r"Microsoft\Windows\Fonts"));
        }
    }
    font_dirs.push(PathBuf::from("/usr/share/fonts"));
    #[cfg(target_os = "macos")]
    {
        font_dirs.push(PathBuf::from("/Library/Fonts"));
        font_dirs.push(PathBuf::from("/System/Library/Fonts"));
    }
    #[cfg(windows)]
    {
        font_dirs.push(PathBuf::from(r"C:\Windows\Fonts"));
    }

    let found_font = font_dirs.into_iter().any(|dir| {
        std::fs::read_dir(dir).is_ok_and(|entries| {
            entries.flatten().any(|e| {
                let name = e.file_name().to_string_lossy().to_ascii_lowercase();
                name.contains("nerd") || name.contains("nf")
            })
        })
    });

    if found_font {
        check("Nerd Font", Level::Ok, "installed (font directory scan)")
    } else {
        check(
            "Nerd Font",
            Level::Info,
            "fc-list unavailable; fonts could not be automatically confirmed",
        )
    }
}

pub fn run_checks(paths: &Paths) -> Vec<Check> {
    let mut out = Vec::new();

    out.push(match runner::version() {
        Some(v) => check("Fastfetch", Level::Ok, v),
        None => check(
            "Fastfetch",
            Level::Fail,
            "not installed - press i to install it with this system's package manager",
        ),
    });

    out.push(match writable(&paths.config_dir) {
        Ok(()) => check(
            "Config dir",
            Level::Ok,
            format!("writable ({})", paths.config_dir.display()),
        ),
        Err(e) => check(
            "Config dir",
            Level::Fail,
            format!("{}: {e}", paths.config_dir.display()),
        ),
    });

    out.push(match paths.preset_logos_dir() {
        Some(dir) => {
            let n = std::fs::read_dir(&dir)
                .map(|rd| {
                    rd.flatten()
                        .filter(|e| e.path().extension().is_some_and(|x| x == "png"))
                        .count()
                })
                .unwrap_or(0);
            check(
                "Assets",
                Level::Ok,
                format!("{n} preset images in {}", dir.display()),
            )
        }
        None => check(
            "Assets",
            Level::Warn,
            format!(
                "preset-logos not found; set {} or install assets",
                crate::paths::ASSETS_ENV
            ),
        ),
    });

    out.push(validate_jsonc("Studio config", &paths.studio_config()));
    out.push(validate_jsonc("Fastfetch config", &paths.fastfetch_config));

    let env = |k: &str| std::env::var(k).unwrap_or_else(|_| "-".into());
    out.push(check(
        "Terminal",
        Level::Info,
        format!("TERM={} TERM_PROGRAM={}", env("TERM"), env("TERM_PROGRAM")),
    ));

    let geo = TermGeometry::detect();
    out.push(check(
        "Cell size",
        if geo.cell_reported {
            Level::Ok
        } else {
            Level::Warn
        },
        format!(
            "{}x{} px per cell, {}x{} cells{}",
            geo.cell.w,
            geo.cell.h,
            geo.cols,
            geo.rows,
            if geo.cell_reported {
                ""
            } else {
                " (terminal reports no pixels; assuming 1:2)"
            }
        ),
    ));

    // What the preview actually draws with (see imaging::kitty / imaging::sixel).
    let wt = if std::env::var_os("WT_SESSION").is_some() {
        "WT_SESSION set"
    } else {
        "no WT_SESSION"
    };
    out.push(if crate::imaging::kitty::detect() {
        check("Logo graphics", Level::Ok, "Kitty protocol, full resolution")
    } else if crate::imaging::sixel::detect() {
        check("Logo graphics", Level::Ok, format!("sixel, full resolution ({wt})"))
    } else {
        check(
            "Logo graphics",
            Level::Warn,
            format!(
                "half blocks, low resolution ({wt}) - set TERMFETCH_STUDIO_GRAPHICS=sixel if your terminal supports sixel"
            ),
        )
    });
    let proto = detect_image_protocol();
    out.push(match proto {
        "chafa" if !has_command("chafa") => check(
            "Image protocol",
            Level::Warn,
            "no native protocol detected and chafa missing; images may not render",
        ),
        "chafa" => check(
            "Image protocol",
            Level::Info,
            "no native protocol detected; using chafa symbols",
        ),
        p => check(
            "Image protocol",
            Level::Ok,
            format!("{p} (native graphics)"),
        ),
    });

    out.push(nerd_font());
    out.push(shell_integration());
    out.push(check(
        "Platform",
        Level::Info,
        format!("{} / {}", std::env::consts::OS, std::env::consts::ARCH),
    ));
    out
}
